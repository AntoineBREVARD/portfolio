<div class="cas-etape">
  <h2>Où, et pour qui</h2>
  <p>Le siège est au <strong>circuit des 24 Heures du Mans</strong>, en Sarthe. Tout y est regroupé : le siège administratif Michel Cosson, le Technoparc, le musée, le circuit et les pistes de karting. Des boutiques à Paris, Tours et Rouen complètent cette implantation.</p>
  <p>L'ACO combine deux clientèles. Côté <strong>grand public</strong> : les spectateurs, les passionnés et les amateurs de sports mécaniques, qui viennent aussi pour le tourisme et les loisirs. Côté <strong>professionnels</strong> : les écuries, les compétiteurs, les sponsors, les partenaires et les entreprises, notamment à travers les offres d'hospitalité.</p>
  <p>Sa responsabilité sociétale est portée par une direction Communication et RSE : actions de sensibilisation des collaborateurs (sécurité, respect, usage des réseaux sociaux) et projets en faveur de l'éducation et de la durabilité.</p>
</div>

<div class="cas-etape">
  <h2>Mon service : le SERI</h2>
  <p>Le SERI ne se limite pas à l'informatique : il regroupe aussi l'<strong>électricité</strong> et l'<strong>audiovisuel</strong>, des métiers étroitement liés pendant les événements, par exemple pour les feux de piste ou la sonorisation du circuit. Le service travaille avec des prestataires, dont un partenaire extérieur chargé de la cybersécurité.</p>
  <p>Onze mois par an, le service fonctionne comme celui d'une PME. Pendant les grandes épreuves, il devient un <strong>centre de commandement</strong> : l'infrastructure s'étend pour accueillir les visiteurs, les écuries et les professionnels, à l'échelle d'une multinationale, sans fenêtre de reprise.</p>
  <p>J'y interviens sur l'administration de Microsoft 365, le support aux utilisateurs, le réseau (brassage, diagnostic, configuration de switches), la gestion de parc et l'automatisation en PowerShell. Pendant les épreuves, je participe à l'installation et à la maintenance des équipements.</p>

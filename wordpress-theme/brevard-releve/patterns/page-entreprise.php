  <h2>Une association née pour la course</h2>
  <p>L'Automobile Club de l'Ouest est une <strong>association loi 1901</strong>, fondée au Mans en 1906 par des passionnés d'automobile. Son objectif d'origine : développer et sécuriser des courses alors très dangereuses. Dès sa création, elle organise en Sarthe le <strong>premier Grand Prix de l'histoire</strong>.</p>
  <p>Après la Première Guerre mondiale, l'ACO invente un nouveau format fondé sur la fiabilité et la résistance des véhicules : l'endurance. Les <strong>24 Heures du Mans</strong> naissent en 1923 et deviennent l'une des courses les plus célèbres au monde. L'ACO est aujourd'hui l'organisateur du championnat du monde d'endurance (WEC) et poursuit son développement autour de l'innovation et de la mobilité durable, notamment l'hydrogène.</p>
